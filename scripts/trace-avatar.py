"""
Traces lib/avatar/style-reference.png into the vector layers the drawn
avatar is built from (components/brand/cartoon-avatar-art.ts), so the
avatar keeps the reference's hand-drawn lines exactly.

    pip install potracer pillow numpy
    python scripts/trace-avatar.py > components/brand/cartoon-avatar-art.ts

Layers, all in the reference's 460x460 space:
  figure  everything that is not background (painted white: collar, teeth)
  skin    the skin areas, grown a little so they sit under the lines
  ink     every black line and shape
  hair    the black of the hair, repainted when the hair is not black
  shirt   the black of the shirt, repainted for other shirt colours
  figureBare, inkBare
          figure and ink without the hair, under a hijab
"""

from collections import deque

import numpy as np
import potrace
from PIL import Image, ImageDraw

SOURCE = 'lib/avatar/style-reference.png'

# Hair: the black above and left of the face (the ear and the face outline below
# the hairline stay ink). Points are in the reference's pixels.
HAIR = [(100, 50), (350, 50), (345, 135), (300, 143), (250, 150), (178, 165), (185, 210),
        (194, 248), (172, 240), (160, 225), (135, 228), (118, 200), (100, 140)]
SHIRT_TOP = 388


def polygon_mask(points, shape):
    img = Image.new('1', (shape[1], shape[0]), 0)
    ImageDraw.Draw(img).polygon(points, fill=1)
    return np.array(img, dtype=bool)


def grow(mask, px):
    out = mask.copy()
    for _ in range(px):
        g = out.copy()
        g[1:, :] |= out[:-1, :]
        g[:-1, :] |= out[1:, :]
        g[:, 1:] |= out[:, :-1]
        g[:, :-1] |= out[:, 1:]
        out = g
    return out


def background(white):
    """White pixels reachable from the border."""
    h, w = white.shape
    seen = np.zeros_like(white)
    q = deque((y, x) for y in range(h) for x in (0, w - 1) if white[y, x])
    q.extend((y, x) for x in range(w) for y in (0, h - 1) if white[y, x])
    for y, x in q:
        seen[y, x] = True
    while q:
        y, x = q.popleft()
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            ny, nx = y + dy, x + dx
            if 0 <= ny < h and 0 <= nx < w and white[ny, nx] and not seen[ny, nx]:
                seen[ny, nx] = True
                q.append((ny, nx))
    return seen


def path(mask):
    # potracer fills the zero pixels, so hand it the inverse.
    curves = potrace.Bitmap(~mask).trace(turdsize=4, alphamax=1.0, opticurve=True, opttolerance=0.2)
    f = lambda p: f'{p.x:.1f} {p.y:.1f}'.replace('.0 ', ' ').replace('.0', '')
    out = []
    for curve in curves:
        out.append(f'M{f(curve.start_point)}')
        for seg in curve:
            if seg.is_corner:
                out.append(f'L{f(seg.c)}L{f(seg.end_point)}')
            else:
                out.append(f'C{f(seg.c1)} {f(seg.c2)} {f(seg.end_point)}')
        out.append('Z')
    return ''.join(out)


def main():
    rgb = np.array(Image.open(SOURCE).convert('RGB')).astype(int)
    lum = rgb.mean(axis=2)
    ink = lum < 110
    white = lum > 225
    # Warm pixels only: the grey soft edges of the lines are not skin.
    skin = ~ink & ~white & (rgb[:, :, 0] > 200) & (rgb[:, :, 0] - rgb[:, :, 2] > 25)
    figure = ~background(white)
    hair = ink & polygon_mask(HAIR, ink.shape)
    shirt = ink.copy()
    shirt[:SHIRT_TOP, :] = False

    layers = {
        'figure': figure,
        'skin': grow(skin, 3) & figure,
        'ink': ink,
        'hair': hair,
        'shirt': shirt,
        # Grown, so the hair's soft grey edge goes too.
        'figureBare': figure & ~grow(hair, 3),
        'inkBare': ink & ~hair,
    }
    print('// Generated by scripts/trace-avatar.py from lib/avatar/style-reference.png; do not edit.')
    print('/* eslint-disable */')
    print('export const ART = {')
    for name, mask in layers.items():
        print(f"  {name}: '{path(mask)}',")
    print('} as const;')


main()
